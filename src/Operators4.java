public class Operators4 {
    public static void main(String[] args)
    {
        System.out.println(64>8);//Comparision  Operator
        System.out.println(64>=65);//comparision Operator
        System.out.println(64>50 && 64>70); //Logical Operator
        System.out.println(64>55 || 64>60);//Logical Operator
        System.out.println(64 % 10);//Arithmetic Operator
        System.out.println(65/5);//Arithmetic Operator
        int i = 10;
        System.out.println(i);//increment and decremnet operator
        System.out.println(i++);//here first value increases and than print in next line
        System.out.println(i);
        System.out.println(++i);//here first value is printed and than increased
    }
}
